import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
const bundle = await build({
  entryPoints: ["src/webview/host.ts"],
  bundle: true,
  platform: "browser",
  format: "iife",
  target: ["es2020"],
  minify: true,
  write: false,
  legalComments: "inline",
});
const script = bundle.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1"><style>html,body,#reader{margin:0;width:100%;height:100%;overflow:hidden}body{background:transparent}</style></head><body><div id="reader"></div><script>${script}</script></body></html>`;
await mkdir("dist/webview", { recursive: true });
await writeFile("dist/webview/reader.html", html);
await writeFile(
  "src/native/reader-html.generated.ts",
  `// Generated by scripts/build-webview.mjs. Do not edit.\nexport const epubReaderHtml = ${JSON.stringify(html)};\n`,
);
console.log(
  `Built self-contained EPUB WebView host (${Math.round(Buffer.byteLength(html) / 1024)} KiB)`,
);
